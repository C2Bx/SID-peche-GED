-- Calendrier genere, pas deduit des dates observees : sinon les jours sans
-- activite manquent et le cumul glissant devient impossible. Cle AAAAMMJJ.
CREATE TABLE DIM_TEMPS (
    temps_key    INT         NOT NULL PRIMARY KEY,
    date_id      DATE        NULL,
    jour         SMALLINT    NULL,
    mois         SMALLINT    NULL,
    trimestre    SMALLINT    NULL,
    annee        SMALLINT    NULL,
    libelle_mois VARCHAR(20) NULL,
    jour_semaine VARCHAR(20) NULL,
    saison       VARCHAR(20) NULL
);

INSERT INTO DIM_TEMPS (temps_key, date_id, jour, mois, trimestre, annee,
                       libelle_mois, jour_semaine, saison)
VALUES (-1, NULL, NULL, NULL, NULL, NULL, 'Inconnu', 'Inconnu', 'Inconnu');

INSERT INTO DIM_TEMPS (temps_key, date_id, jour, mois, trimestre, annee,
                       libelle_mois, jour_semaine, saison)
SELECT TO_CHAR(d, 'YYYYMMDD')::INT, d,
       EXTRACT(DAY FROM d)::SMALLINT,
       EXTRACT(MONTH FROM d)::SMALLINT,
       EXTRACT(QUARTER FROM d)::SMALLINT,
       EXTRACT(YEAR FROM d)::SMALLINT,
       -- Libelles fixes : TO_CHAR('TMMonth') depend de lc_time du serveur et
       -- complete le nom par des espaces ; les deux moteurs doivent concorder.
       (ARRAY['Janvier','Février','Mars','Avril','Mai','Juin','Juillet',
              'Août','Septembre','Octobre','Novembre','Décembre'])
           [EXTRACT(MONTH FROM d)::INT],
       (ARRAY['Lundi','Mardi','Mercredi','Jeudi','Vendredi','Samedi',
              'Dimanche'])[EXTRACT(ISODOW FROM d)::INT],
       CASE WHEN EXTRACT(MONTH FROM d)::INT IN (12,1,2) THEN 'Été'     -- hemisphere sud
            WHEN EXTRACT(MONTH FROM d)::INT IN (3,4,5)  THEN 'Automne'
            WHEN EXTRACT(MONTH FROM d)::INT IN (6,7,8)  THEN 'Hiver'
            ELSE 'Printemps' END
FROM GENERATE_SERIES(DATE '1990-01-01', DATE '2050-12-31', INTERVAL '1 day') AS jours(d);


CREATE TABLE DIM_COMMUNE (
    commune_key INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL PRIMARY KEY,
    commune     VARCHAR(200) NULL
);

INSERT INTO DIM_COMMUNE (commune_key, commune) VALUES (-1, 'Non renseignée');

-- La commune apparait dans trois colonnes sources.
INSERT INTO DIM_COMMUNE (commune)
SELECT DISTINCT BTRIM(c)
FROM (
    SELECT capitaine_commune AS c FROM env_mer.pecheur_anonymise
    UNION SELECT patron_pecheur_commune FROM env_mer.pecheur_anonymise
    UNION SELECT carte_autorisation_commune FROM env_mer.pecheur_anonymise
) AS x
WHERE c IS NOT NULL AND BTRIM(c) <> '';


-- Capitaines et patrons fusionnes, UNE SEULE LIGNE PAR PERSONNE.
-- Le grain doit etre strictement la personne : les faits joignent sur
-- personne_id, et un doublon y ferait enfler la jointure jusqu'a violer la
-- cle primaire de FAIT_CARTE. Grouper sur la commune produisait ce doublon
-- pour les 3 personnes dont la commune varie d'un role a l'autre ; la
-- commune est donc agregee comme les autres attributs.
CREATE TABLE DIM_PERSONNE (
    personne_key    INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL PRIMARY KEY,
    personne_id     VARCHAR(255) NULL,
    commune_key     INT          NOT NULL,
    date_naissance  DATE         NULL,
    annee_naissance SMALLINT     NULL,
    sexe            VARCHAR(60)  NULL,
    est_capitaine   BOOLEAN      NOT NULL,
    est_patron      BOOLEAN      NOT NULL
);

INSERT INTO DIM_PERSONNE (personne_key, personne_id, commune_key,
                          date_naissance, annee_naissance, sexe,
                          est_capitaine, est_patron)
VALUES (-1, NULL, -1, NULL, NULL, 'Inconnu', FALSE, FALSE);

WITH roles AS (
    SELECT capitaine_id AS personne_id, capitaine_commune AS commune,
           capitaine_date_naissance AS naissance, capitaine_sexe AS sexe,
           1 AS capitaine, 0 AS patron
    FROM env_mer.pecheur_anonymise
    WHERE capitaine_id IS NOT NULL
    UNION ALL
    SELECT patron_pecheur_id, patron_pecheur_commune,
           patron_pecheur_date_naissance, patron_pecheur_sexe, 0, 1
    FROM env_mer.pecheur_anonymise
    WHERE patron_pecheur_id IS NOT NULL
)
INSERT INTO DIM_PERSONNE (personne_id, commune_key, date_naissance,
                          annee_naissance, sexe, est_capitaine, est_patron)
SELECT r.personne_id,
       MAX(COALESCE(dc.commune_key, -1)),
       MAX(r.naissance),
       CASE WHEN EXTRACT(YEAR FROM MAX(r.naissance)) BETWEEN 1900 AND 2030
            THEN EXTRACT(YEAR FROM MAX(r.naissance))::SMALLINT END,
       MAX(r.sexe),
       MAX(r.capitaine) = 1, MAX(r.patron) = 1
FROM roles r
LEFT JOIN DIM_COMMUNE dc ON dc.commune = BTRIM(r.commune)
GROUP BY r.personne_id;


CREATE TABLE DIM_CARTE (
    carte_key                   INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL PRIMARY KEY,
    carte_id                    VARCHAR(255) NULL,
    carte_type                  VARCHAR(120) NULL,
    carte_type_source           VARCHAR(120) NULL,
    carte_annee                 VARCHAR(20)  NULL,
    carte_renouvellement        BOOLEAN      NULL,
    carte_autorisation_statut   VARCHAR(120) NULL,
    carte_autorisation_annee    VARCHAR(20)  NULL,
    commune_key                 INT          NOT NULL,
    carte_autorisation_province VARCHAR(120) NULL
);

INSERT INTO DIM_CARTE (carte_key, carte_id, carte_type, carte_type_source,
                       commune_key)
VALUES (-1, NULL, 'Inconnu', NULL, -1);

-- La source porte cinq orthographes pour deux types de carte, dont une
-- doublement encodee. On normalise et on garde la variante brute.
INSERT INTO DIM_CARTE (carte_id, carte_type, carte_type_source, carte_annee,
                       carte_renouvellement, carte_autorisation_statut,
                       carte_autorisation_annee, commune_key,
                       carte_autorisation_province)
SELECT p.carte_id,
       CASE
         WHEN p.carte_type LIKE 'C%ti%re' OR p.carte_type LIKE 'C%tiere' THEN 'Côtière'
         WHEN p.carte_type LIKE 'Ha%ri%re' OR p.carte_type LIKE 'Haut%'  THEN 'Hauturière'
         ELSE p.carte_type
       END,
       p.carte_type,
       p.carte_annee, p.carte_renouvellement, p.carte_autorisation_statut,
       p.carte_autorisation_annee,
       COALESCE(dc.commune_key, -1),
       p.carte_autorisation_province
FROM env_mer.pecheur_anonymise p
LEFT JOIN DIM_COMMUNE dc
       ON dc.commune = BTRIM(p.carte_autorisation_commune);


-- nb_moteurs est un attribut legitime du navire. Le detail des moteurs vit
-- dans DIM_MOTEUR : 24 navires en portent plusieurs, et retenir MAX(marque)
-- et MAX(carburant) independamment pouvait produire un couple qui n'existe
-- dans aucun moteur reel.
CREATE TABLE DIM_NAVIRE (
    navire_key            INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL PRIMARY KEY,
    navire_id             VARCHAR(255) NULL,
    annee_construction    INT          NULL,
    longueur              DOUBLE PRECISION NULL,
    tranche_longueur      VARCHAR(30)  NULL,
    jauge_brute           DOUBLE PRECISION NULL,
    origine               VARCHAR(120) NULL,
    categorie_navigation  VARCHAR(120) NULL,
    materiau              VARCHAR(120) NULL,
    constructeur          VARCHAR(200) NULL,
    nb_moteurs            INT          NULL
);

INSERT INTO DIM_NAVIRE (navire_key, navire_id, tranche_longueur, nb_moteurs)
VALUES (-1, NULL, 'Inconnue', 0);

INSERT INTO DIM_NAVIRE (navire_id, annee_construction, longueur,
                        tranche_longueur, jauge_brute, origine,
                        categorie_navigation, materiau, constructeur,
                        nb_moteurs)
SELECT n.navire_id,
       CASE
         WHEN BTRIM(n.navire_annee_construction) ~ '^[+-]?[0-9]+$' THEN
           CASE
             WHEN BTRIM(n.navire_annee_construction)::NUMERIC BETWEEN -2147483648 AND 2147483647
             THEN BTRIM(n.navire_annee_construction)::INT
             ELSE NULL
           END
         ELSE NULL
       END,  -- equivalent TRY_CONVERT(INT, ...)
       CASE WHEN n.navire_longueur > 0 THEN n.navire_longueur END,
       CASE WHEN n.navire_longueur IS NULL OR n.navire_longueur <= 0 THEN 'Inconnue'
            WHEN n.navire_longueur <  6 THEN 'Moins de 6 m'
            WHEN n.navire_longueur < 10 THEN '6 à 10 m'
            WHEN n.navire_longueur < 15 THEN '10 à 15 m'
            ELSE '15 m et plus' END,
       CASE WHEN n.navire_jauge_brute > 0 THEN n.navire_jauge_brute END,
       n.navire_origine, n.categorie_navigation, n.materiau, n.constructeur,
       COALESCE(m.nb, 0)
FROM env_mer.navire_peche_anonymise n
LEFT JOIN (
    SELECT navire_id, COUNT(*) AS nb
    FROM env_mer.navire_moteur
    GROUP BY navire_id
) m ON m.navire_id = n.navire_id;


-- Un moteur appartient a un seul navire : la relation est 1-N, une table de
-- pont serait inutile. Le couple marque/carburant reste ici celui d'un moteur
-- reel, jamais une recomposition.
CREATE TABLE DIM_MOTEUR (
    moteur_key   INT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL PRIMARY KEY,
    moteur_id    VARCHAR(255) NULL,
    navire_key   INT          NOT NULL,
    usage_moteur VARCHAR(200) NULL,
    marque       VARCHAR(200) NULL,
    carburant    VARCHAR(60)  NULL
);

INSERT INTO DIM_MOTEUR (moteur_key, moteur_id, navire_key, usage_moteur,
                        marque, carburant)
VALUES (-1, NULL, -1, 'Inconnu', 'Inconnue', 'Inconnu');

INSERT INTO DIM_MOTEUR (moteur_id, navire_key, usage_moteur, marque, carburant)
SELECT m.moteur_id, COALESCE(n.navire_key, -1),
       LEFT(m.usage, 200), LEFT(m.marque, 200), LEFT(m.carburant, 60)
FROM env_mer.navire_moteur m
LEFT JOIN DIM_NAVIRE n ON n.navire_id = m.navire_id;


-- Cle de substitution : une PK (categorie_code, produit) porterait sur du
